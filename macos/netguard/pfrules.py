"""pf kill-switch rules and the only pf operations NetGuard performs.

Safety contract (verified by tests):
- Only the anchor com.apple/zz.NetGuard is loaded or flushed. /etc/pf.conf and the
  main ruleset are never written, so other pf users (ClaudeGuard, Internet Sharing,
  VPN apps) keep their anchors.
- pf is enabled with a reference token (`pfctl -E`) and released with `pfctl -X`,
  never with a global `pfctl -d`.
- Global states are never flushed.

Rule semantics mirror the Windows WFP design: block every outbound packet, then let
later (last-match) rules permit the proxy TUN, the proxy core, LAN/link-local and
loopback. Pass rules are not `quick`, so another tool's `block quick` (ClaudeGuard)
still wins; the default block is overridden only by our own permits.
"""
import hashlib
import re

from . import paths, util


class PFError(RuntimeError):
    pass


def _list(values):
    return "{ " + ", ".join(values) + " }"


def render(cfg, core_uid, core_gid):
    """Anchor text. core_uid/core_gid identify the FlClash core's sockets.

    FlClash authorizes its core for TUN with `chown root:admin; chmod 4750`, so the
    core runs with effective uid 0 and the launching user's group (normally staff=20).
    Root daemons run with group wheel (0) and ordinary apps with uid != 0, so neither
    matches. gid 0 would exempt every root daemon and is refused.
    """
    core_uid = int(core_uid)
    core_gid = int(core_gid)
    if core_uid != 0:
        raise PFError("代理内核必须以 root 身份运行（FlClash 需开启 TUN 并授权内核）")
    if core_gid == 0:
        raise PFError("代理内核的用户组是 wheel(0)，放行它会放行所有 root 后台程序，拒绝生成规则")
    tun4, tun6 = cfg["tun_v4"], cfg["tun_v6"]
    lines = [
        "# NetGuard kill switch for macOS. Generated by NetGuard; do not edit.",
        "# Loaded only into anchor %s. /etc/pf.conf is never modified." % paths.ANCHOR,
        "",
        "# Loopback is always allowed.",
        'pass out quick on lo0 all no state label "ng_loopback"',
        "",
        "# Anthropic's published ranges: refused on every path except the proxy TUN, so a",
        "# DIRECT rule or a dropped tunnel cannot reach Claude with the real IP.",
    ]
    if cfg["anthropic_v4"]:
        lines.append('block return out quick inet from ! %s to %s label "ng_anthropic"'
                     % (tun4, _list(cfg["anthropic_v4"])))
    if cfg["anthropic_v6"]:
        lines.append('block return out quick inet6 from ! %s to %s label "ng_anthropic"'
                     % (tun6, _list(cfg["anthropic_v6"])))
    lines += [
        "",
        "# Default: no outbound traffic. Later permits override this (last match wins).",
        'block return out all label "ng_block_all"',
        "",
        "# LAN, link-local, multicast and broadcast (DHCP, router, printers, AirDrop).",
        'pass out inet to %s keep state label "ng_lan"' % _list(cfg["lan_v4"]),
        'pass out inet proto tcp to %s flags any keep state label "ng_lan"' % _list(cfg["lan_v4"]),
        'pass out inet6 to %s keep state label "ng_lan"' % _list(cfg["lan_v6"]),
        'pass out inet6 proto tcp to %s flags any keep state label "ng_lan"' % _list(cfg["lan_v6"]),
    ]
    if cfg["block_lan_dns"]:
        lines += [
            "",
            "# DNS outside the TUN is refused, including the LAN router (opt-in).",
            'block return out proto { tcp, udp } to port 53 label "ng_dns"',
        ]
    lines += [
        "",
        "# Everything routed into the proxy TUN carries the TUN source address.",
        'pass out inet from %s keep state label "ng_tun"' % tun4,
        'pass out inet proto tcp from %s flags any keep state label "ng_tun"' % tun4,
        'pass out inet6 from %s keep state label "ng_tun"' % tun6,
        'pass out inet6 proto tcp from %s flags any keep state label "ng_tun"' % tun6,
        "",
        "# The proxy core itself (FlClash setuid core: uid %d, group %d)." % (core_uid, core_gid),
        'pass out proto udp all user %d group %d keep state label "ng_core"' % (core_uid, core_gid),
        'pass out proto tcp all user %d group %d flags any keep state label "ng_core"' % (core_uid, core_gid),
        "",
    ]
    return "\n".join(lines)


def parse_token(output):
    match = re.search(r"Token\s*:\s*(\d+)", output or "")
    return match.group(1) if match else None


def token_in_references(token, references):
    if not token:
        return False
    for line in (references or "").splitlines():
        fields = line.split()
        if len(fields) >= 3 and fields[0].isdigit() and token in fields[1:]:
            return True
    return False


def normalize_rules(text):
    return "\n".join(line.rstrip() for line in (text or "").splitlines() if line.strip())


def fingerprint(text):
    return hashlib.sha256(normalize_rules(text).encode("utf-8")).hexdigest()


MAIN_ANCHOR_RE = re.compile(r'^anchor "com\.apple/\*"', re.M)


class PF:
    def __init__(self, runner=util.run):
        self.runner = runner

    def _pf(self, *args, input=None, check=True):
        result = self.runner([paths.PFCTL] + list(args), input=input, timeout=20)
        if check and result.returncode != 0:
            raise PFError("pfctl %s 失败：%s" % (" ".join(args), (result.stderr or "").strip()[:300]))
        return result

    # ---- read-only ----
    def check_syntax(self, text):
        self._pf("-n", "-a", paths.ANCHOR, "-f", "-", input=text)

    def anchor_rules(self):
        return self._pf("-a", paths.ANCHOR, "-sr").stdout

    def main_rules(self):
        return self._pf("-sr").stdout

    def enabled(self):
        out = self._pf("-s", "info").stdout
        return bool(re.search(r"^Status:\s*Enabled", out, re.M))

    def references(self):
        return self._pf("-s", "References").stdout

    def labels(self):
        return self._pf("-a", paths.ANCHOR, "-s", "labels", check=False).stdout

    # ---- mutations (anchor-scoped) ----
    def load(self, text):
        self.check_syntax(text)
        self._pf("-a", paths.ANCHOR, "-f", "-", input=text)

    def flush(self):
        # rules only: never `-F all`, which would also flush every connection state.
        self._pf("-a", paths.ANCHOR, "-F", "rules", check=False)

    def acquire_token(self, token):
        """Keep exactly one live reference. Returns the (possibly new) token."""
        if token and token_in_references(token, self.references()):
            return token
        result = self._pf("-E")
        token = parse_token((result.stdout or "") + "\n" + (result.stderr or ""))
        if not token:
            raise PFError("pfctl -E 未返回 token")
        return token

    def release_token(self, token):
        if token and token_in_references(token, self.references()):
            self._pf("-X", token, check=False)

    def integrity(self, expected_fp):
        out = {"pf_enabled": False, "main_anchor_ref": False, "rules_match": False,
               "rule_count": 0, "error": None, "read_error": None}
        try:
            out["pf_enabled"] = self.enabled()
            out["main_anchor_ref"] = bool(MAIN_ANCHOR_RE.search(self.main_rules()))
            rules = self.anchor_rules()
            out["rule_count"] = len(normalize_rules(rules).splitlines())
            out["rules_match"] = bool(expected_fp) and fingerprint(rules) == expected_fp \
                and "ng_block_all" in rules
        except PFError as exc:
            out["read_error"] = str(exc)
        out["complete"] = bool(out["pf_enabled"] and out["main_anchor_ref"] and out["rules_match"])
        return out
